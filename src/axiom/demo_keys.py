"""Generate the keyless demo's secrets on first start, so `docker compose up` needs no setup.

The `demo-keys` service runs this once before the other containers start. It writes the MCP
shared secret and one API key per role to a file (default `.demo/keys.env` in the repo),
which every container reads through `docker/with-demo-keys.sh`. A value set in `.env` always
wins; generated values only fill what `.env` leaves empty. The file is kept across restarts,
so the keys stay the same until it is deleted.

These are local demo keys: they open a stack bound to 127.0.0.1 and holding synthetic data.

    python -m axiom.demo_keys /run/axiom-demo/keys.env
"""

from __future__ import annotations

import os
import re
import secrets
import sys
from pathlib import Path

DEFAULT_PATH = Path("/run/axiom-demo/keys.env")
NAME = re.compile(r"^[A-Z][A-Z0-9_]*$")
# Each role key's principal name, and how the review page describes the role.
ROLES = {
    "SUBMITTER_API_KEYS": ("rm-demo", "Relationship manager"),
    "REVIEWER_API_KEYS": ("co-demo", "Credit officer"),
    "AUDITOR_API_KEYS": ("audit-demo", "Auditor"),
}


def generate() -> dict[str, str]:
    values = {"MCP_SHARED_SECRET": secrets.token_hex(32)}
    for var, (name, _) in ROLES.items():
        values[var] = f"{name}:{secrets.token_hex(24)}"
    return values


def read(path: Path) -> dict[str, str]:
    values = {}
    for line in path.read_text().splitlines():
        key, sep, value = line.partition("=")
        if sep and NAME.match(key):
            values[key] = value
    return values


def write(path: Path, values: dict[str, str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    body = "".join(f"{k}={v}\n" for k, v in values.items())
    tmp = path.with_suffix(".tmp")
    tmp.write_text("# Generated by the demo-keys service. Local demo only; never commit.\n" + body)
    # Readable by the other containers, which run as different users.
    tmp.chmod(0o644)
    tmp.replace(path)


def ensure(path: Path) -> tuple[dict[str, str], bool]:
    """The keys in `path`, generating them first if the file is missing or incomplete."""
    if path.is_file():
        values = read(path)
        if all(values.get(k) for k in ("MCP_SHARED_SECRET", *ROLES)):
            return values, False
    values = generate()
    write(path, values)
    return values, True


def summary(values: dict[str, str], created: bool, env: dict[str, str]) -> str:
    lines = [
        "Axiom demo keys: " + ("generated now" if created else "kept from an earlier start"),
        "Open http://localhost:8000/review and sign in with one of these keys:",
    ]
    shown = False
    for var, (_, label) in ROLES.items():
        if env.get(var):
            lines.append(f"  {label + ':':<22} set in your .env (not shown)")
        else:
            lines.append(f"  {label + ':':<22} {values[var].partition(':')[2]}")
            shown = True
    if shown:
        lines.append("The keys are also in .demo/keys.env. Delete that file to get new ones.")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    path = Path(argv[1]) if len(argv) > 1 else DEFAULT_PATH
    values, created = ensure(path)
    print(summary(values, created, dict(os.environ)), flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
